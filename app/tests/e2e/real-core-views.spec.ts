/**
 * The three views the fake core hid, driven against the REAL core.
 *
 * `docs/GUI-AUDIT.md` found the renderer wired to `mapped-netlist`,
 * `provenance` and `analyse` while the CLI registered none of them, so the
 * schematic's netlist, the linked-selection spine and the analysis dashboard
 * were all dead in the real app — and every test passed because every test
 * asked the fake. `contract-commands.spec.ts` now makes that class of defect
 * impossible; this spec makes it *visible*, by exercising the three views
 * against the real Python core.
 *
 * Like the GUI-audit regressions, these are hermetic: they seed the netlist
 * files a real `gatepack build` would have written (`mapped.json`, `packed.json`,
 * `premap.json`, `cells.lib`) so no Yosys is needed. There is deliberately no
 * `test.skip` here: if the real core is unavailable the launch helper throws and
 * the test FAILS — a skip is not a pass, for the same reason the `toolchain` CI
 * job greps its own log for "skipped".
 */

