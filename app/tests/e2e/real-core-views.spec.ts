let realCorePath: string | null = null;

function getRealCore(): string | null {
  const py = path.join(REPO_ROOT, '.venv', 'bin', 'python');
  if (!fs.existsSync(py)) return null;
  if (realCorePath === null) {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gatepack-realcore-'));
    realCorePath = path.join(dir, 'gatepack');
    // PYTHONPATH is required: the core is spawned with cwd = the opened project
    // directory, so `python -m gatepack.cli` only resolves when PYTHONPATH points
    // at the repo root (the same thing `main/core.cts` does for `.venv/bin/python`).
    fs.writeFileSync(
      realCorePath,
      `#!/bin/sh\nexport PYTHONPATH="${REPO_ROOT}"\nexec "${py}" -m gatepack.cli "$@"\n`,
    );
    fs.chmodSync(realCorePath, 0o755);
  }
  return realCorePath;
}

interface Launched {
  app: ElectronApplication;
  page: Page;
}

async function launchRealCoreApp(): Promise<Launched> {
  const core = getRealCore();
  if (core === null) {
    // No skip: a missing real core is a failed test, never a quietly skipped one.
    throw new Error('real core not locatable (.venv/bin/python)');
  }
  const app = await _electron.launch({
    args: [APP_DIR],
    env: {
      ...process.env,
      GATEPACK_CORE: core,
      GATEPACK_SESSION_DIR: fs.mkdtempSync(path.join(os.tmpdir(), 'gatepack-session-')),
    },
  });
  const page = await app.firstWindow();
  await page.waitForFunction(() => typeof (window as any).gatepack !== 'undefined');
  return { app, page };
}

/** A project directory seeded with `design.yaml` plus the given `.gatepack/out` files. */
function makeProjectDir(outFiles: Record<string, string>, design = DESIGN): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gatepack-views-'));
  fs.writeFileSync(path.join(dir, 'design.yaml'), design);
  const out = path.join(dir, '.gatepack', 'out');
  fs.mkdirSync(out, { recursive: true });
  for (const [name, content] of Object.entries(outFiles)) {
    fs.writeFileSync(path.join(out, name), content);
  }
  return dir;
}

test.describe('real-core views', () => {
  let launched: Launched | null = null;

  test.afterEach(async () => {
    if (launched) {
      await launched.app.close();
      launched = null;
    }
  });

  test('the schematic renders the mapped netlist from the real core', async () => {
    launched = await launchRealCoreApp();
    const page = launched.page;

    const dir = makeProjectDir({ 'mapped.json': MAPPED_JSON, 'packed.json': PACKED_JSON });
    const opened = await page.evaluate(
      (p) => (window as any).gatepack.openProjectPath(p),
      dir,
    );
    expect(opened.ok).toBe(true);

    await page.getByTestId('nav-schematic').click();
    // The schematic draws an SVG from `gatepack mapped-netlist` + `packed-netlist`;
    // a dead command surfaces GP9002 as `schematic-error` instead.
    const svg = page.locator('[data-testid="schematic-svg"] svg');
    await expect(svg).toHaveCount(1, { timeout: 30_000 });
    await expect(page.locator('[data-testid="schematic-error"]')).toHaveCount(0);
  });

  test('the provenance spine returns real links from the real core', async () => {
    launched = await launchRealCoreApp();
    const page = launched.page;

    const outFiles = {
      'premap.json': fs.readFileSync(path.join(FIXTURES, 'premap.json'), 'utf8'),
      'mapped.json': fs.readFileSync(path.join(FIXTURES, 'mapped.json'), 'utf8'),
      'post_abc.json': fs.readFileSync(path.join(FIXTURES, 'post_abc.json'), 'utf8'),
    };
    const dir = makeProjectDir(outFiles);
    const opened = await page.evaluate(
      (p) => (window as any).gatepack.openProjectPath(p),
      dir,
    );
    expect(opened.ok).toBe(true);

    const env = await page.evaluate(() => (window as any).gatepack.provenance());
    expect(env.ok, JSON.stringify(env)).toBe(true);
    expect(env.data.coverage).toBeGreaterThan(0);

    // The spine's data contract: `output_logic.y` links exactly to the `y_int`
    // net (the combinational carrier), with a surviving attribute.
    const entries = env.data.entries as Array<{ pointer: string; nets: string[]; confidence: string }>;
    const outputLogic = entries.find((e) => e.pointer.endsWith('output_logic.y'));
    expect(outputLogic).toBeTruthy();
    expect(outputLogic!.confidence).toBe('exact');
    expect(outputLogic!.nets).toContain('y_int');
  });

  test('the analysis dashboard renders metrics from the real core', async () => {
    launched = await launchRealCoreApp();
    const page = launched.page;

    const dir = makeProjectDir({
      'mapped.json': MAPPED_JSON,
      'cells.lib': CELLS_LIB,
      'generated.v': 'module t;\nendmodule\n',
    });
    const opened = await page.evaluate(
      (p) => (window as any).gatepack.openProjectPath(p),
      dir,
    );
    expect(opened.ok).toBe(true);

    await page.getByTestId('nav-analysis').click();
    await page.getByRole('button', { name: 'Run analysis' }).click();

    // `analyse` succeeded and the dashboard shows the stuck-at classification,
    // not the `analysis-error` note that a dead command (GP9002) would produce.
    await expect(page.locator('[data-testid="fault-detected"]')).toBeVisible({ timeout: 30_000 });
    await expect(page.locator('[data-testid="analysis-error"]')).toHaveCount(0);
  });
});
